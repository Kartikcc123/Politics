function decodeSecWord(word) {
  if (!word) return '';
  let w = word.trim();
  if (!w) return '';

  if (exactWordMap[w]) {
    return exactWordMap[w];
  }

  // Compound / Suffix splits
  if (w.endsWith('दकरल') || w.endsWith('दक रल')) {
    const prefix = w.replace(/दक\s*रल$|दकरल$/, '');
    return (decodeSecWord(prefix) + ' देवी').trim();
  }
  if (w.endsWith('बरई') || w.endsWith('बर ई')) {
    const prefix = w.replace(/बर\s*ई$|बरई$/, '');
    return (decodeSecWord(prefix) + ' बाई').trim();
  }
  if (w.endsWith('करबरर') || w.endsWith('कर बरर')) {
    const prefix = w.replace(/कर\s*बरर$|करबरर$/, '');
    return (decodeSecWord(prefix) + ' कंवर').trim();
  }
  if (w.endsWith('लरल')) {
    const prefix = w.slice(0, -3);
    return (decodeSecWord(prefix) + ' लाल').trim();
  }
  if (w.endsWith('कचमररत') || w.endsWith('कच मररत') || w.endsWith('कपमररत') || w.endsWith('कप मररत')) {
    const prefix = w.replace(/(कच|कप)\s*मररत$/, '');
    return (decodeSecWord(prefix) + ' कुमावत').trim();
  }
  if (w.endsWith('कचमररल') || w.endsWith('कच मररल')) {
    const prefix = w.replace(/कच\s*मररल$/, '');
    return (decodeSecWord(prefix) + ' कुमारी').trim();
  }
  if (w.endsWith('कचमरर') || w.endsWith('कच मरर') || w.endsWith('कपमरर') || w.endsWith('कप मरर')) {
    const prefix = w.replace(/(कच|कप)\s*मरर$/, '');
    return (decodeSecWord(prefix) + ' कुमार').trim();
  }
  if (w.endsWith('लसह') || w.endsWith('लसपह') || w.endsWith('ससह')) {
    const prefix = w.replace(/(लस\s*पह|लसह|ससह)$/, '');
    return (decodeSecWord(prefix) + ' सिंह').trim();
  }
  if (w.endsWith('चनन') || w.endsWith('चनद') || w.endsWith('चपन') || w.endsWith('चपद')) {
    const prefix = w.replace(/(चनन|चनद|चपन|चपद)$/, '');
    return (decodeSecWord(prefix) + ' चन्द्र').trim();
  }
  if (w.endsWith('शमरर')) {
    const prefix = w.replace(/शमरर$/, '');
    return (decodeSecWord(prefix) + ' शर्मा').trim();
  }
  if (w.endsWith('दरस')) {
    const prefix = w.replace(/दरस$/, '');
    return (decodeSecWord(prefix) + ' दास').trim();
  }

  // Segment matches
  let res = w;

  // Compound clusters
  res = res.replace(/ससरन/g, 'स्थान');
  res = res.replace(/ककत/g, 'क्षेत्र');
  res = res.replace(/दकरल/g, 'देवी');
  res = res.replace(/दकरर/g, 'देवा');
  res = res.replace(/लरलल/g, 'लाली');
  res = res.replace(/लरल/g, 'लाल');
  res = res.replace(/करबरर/g, 'कंवर');
  res = res.replace(/बरई/g, 'बाई');
  res = res.replace(/(कच|कप)\s*मरर/g, 'कुमार');
  res = res.replace(/(कच|कप)\s*मररल/g, 'कुमारी');
  res = res.replace(/(कच|कप)\s*मररत/g, 'कुमावत');
  res = res.replace(/गचजर/g, 'गुर्जर');
  res = res.replace(/गपजर/g, 'गुर्जर');
  res = res.replace(/सपखजर/g, 'संख्या');
  res = res.replace(/मकरन/g, 'मकान');
  res = res.replace(/ननरररचन/g, 'निर्वाचन');
  res = res.replace(/ननरररचक/g, 'निर्वाचक');
  res = res.replace(/पपचरजत/g, 'पंचायत');
  res = res.replace(/ररधकशजरम/g, 'राधेश्याम');
  res = res.replace(/अशयक/g, 'अशोक');
  res = res.replace(/सपगलतर/g, 'संगीता');
  res = res.replace(/मनलष/g, 'मनीष');
  res = res.replace(/नरनयद/g, 'विनोद');
  res = res.replace(/सचनमतर/g, 'सुमित्रा');
  res = res.replace(/जगदलश/g, 'जगदीश');
  res = res.replace(/रमकश/g, 'रमेश');
  res = res.replace(/लकमल/g, 'लक्ष्मी');

  // Phonetic passes for Devanagari consonants if encoded in legacy 8-bit format:
  if (/[नकरयचबप][क-ह]/.test(res) || /[क-ह][नकरयचबप]/.test(res)) {
    // 1. 'न' before consonant -> 'ि' (choti ee matra placed after consonant)
    res = res.replace(/न([क-ह])/g, '$1ि');

    // 2. 'र' after consonant -> 'ा' (aa matra)
    res = res.replace(/([क-ह])र/g, '$1ा');

    // 3. 'क' after consonant -> 'े' (e matra)
    res = res.replace(/([क-ह])क/g, '$1े');

    // 4. 'य' after consonant -> 'ो' (o matra)
    res = res.replace(/([क-ह])य/g, '$1ो');

    // 5. 'च' after consonant -> 'ु' (u matra)
    res = res.replace(/([क-ह])च/g, '$1ु');

    // 6. 'ब' after consonant -> 'ू' (oo matra)
    res = res.replace(/([क-ह])ब/g, '$1ू');

    // 7. 'प' as anusvara / bindu
    res = res.replace(/([क-ह])प/g, '$1ं');
    res = res.replace(/प([क-ह])/g, '$1ं');
  }

  // Clean double matras if any
  res = res.replace(/([ािीुूेैोौं])\1+/g, '$1');

  return res.trim();
}

function decodeSecHindi(text) {
  if (!text) return '';
  let clean = text
    .replace(/Photo\s*is\s*Available/gi, '')
    .replace(/Available/gi, '')
    .replace(/Photo/gi, '')
    .replace(/is/gi, '')
    .trim();

  if (!clean) return '';

  const words = clean.split(/\s+/);
  const decoded = words.map(w => decodeSecWord(w));
  return decoded.join(' ').replace(/\s{2,}/g, ' ').trim();
}

