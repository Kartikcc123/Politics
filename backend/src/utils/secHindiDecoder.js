function decodeSecWord(word) {
  if (!word) return '';
  let w = word.trim();
  if (!w) return '';

  if (exactWordMap[w]) {
    return exactWordMap[w];
  }

  // Common suffix / prefix splits
  if (w.endsWith('दकरल') || w.endsWith('दक रल')) {
    const prefix = w.replace(/दक\s*रल$|दकरल$/, '');
    return (decodeSecWord(prefix) + ' देवी').trim();
  }
  if (w.endsWith('लरल')) {
    const prefix = w.slice(0, -3);
    return (decodeSecWord(prefix) + ' लाल').trim();
  }
  if (w.endsWith('कचमररत') || w.endsWith('कच मररत')) {
    const prefix = w.replace(/कच\s*मररत$/, '');
    return (decodeSecWord(prefix) + ' कुमावत').trim();
  }
  if (w.endsWith('कचमररल') || w.endsWith('कच मररल')) {
    const prefix = w.replace(/कच\s*मररल$/, '');
    return (decodeSecWord(prefix) + ' कुमारी').trim();
  }
  if (w.endsWith('कचमरर') || w.endsWith('कच मरर')) {
    const prefix = w.replace(/कच\s*मरर$/, '');
    return (decodeSecWord(prefix) + ' कुमार').trim();
  }
  if (w.endsWith('लसह') || w.endsWith('लसपह')) {
    const prefix = w.replace(/लस\s*पह$|लसह$/, '');
    return (decodeSecWord(prefix) + ' सिंह').trim();
  }

  let res = w;

  // Compound clusters
  res = res.replace(/ससरन/g, 'स्थान');
  res = res.replace(/ककत/g, 'क्षेत्र');
  res = res.replace(/दकरल/g, 'देवी');
  res = res.replace(/दकरर/g, 'देवा');
  res = res.replace(/लरलल/g, 'लाली');
  res = res.replace(/लरल/g, 'लाल');
  res = res.replace(/कच\s*मरर/g, 'कुमार');
  res = res.replace(/कच\s*मररल/g, 'कुमारी');
  res = res.replace(/कच\s*मररत/g, 'कुमावत');
  res = res.replace(/गचजर/g, 'गुर्जर');
  res = res.replace(/गपजर/g, 'गुर्जर');
  res = res.replace(/सपखजर/g, 'संख्या');
  res = res.replace(/मकरन/g, 'मकान');
  res = res.replace(/ननरररचन/g, 'निर्वाचन');
  res = res.replace(/ननरररचक/g, 'निर्वाचक');
  res = res.replace(/पपचरजत/g, 'पंचायत');

  // Phonetic passes for Devanagari consonants:
  // 1. 'न' before consonant -> 'ि' (choti ee matra placed after consonant)
  res = res.replace(/न([क-ह])/g, '$1ि');

  // 2. 'र' after consonant -> 'ा' (aa matra)
  res = res.replace(/([क-ह])र/g, '$1ा');

  // 3. 'ल' after consonant -> 'ी' (ee matra) (except when word is just 'मल' or 'लाल')
  if (res !== 'मल' && res !== 'लाल') {
    res = res.replace(/([क-ह])ल/g, '$1ी');
  }

  // 4. 'क' after consonant -> 'े' (e matra)
  res = res.replace(/([क-ह])क/g, '$1े');

  // 5. 'य' after consonant -> 'ो' (o matra)
  res = res.replace(/([क-ह])य/g, '$1ो');

  // 6. 'च' after consonant -> 'ु' (u matra)
  res = res.replace(/([क-ह])च/g, '$1ु');

  // 7. 'ब' after consonant -> 'ू' (oo matra)
  res = res.replace(/([क-ह])ब/g, '$1ू');

  // 8. 'प' as anusvara / bindu
  res = res.replace(/([क-ह])प/g, '$1ं');
  res = res.replace(/प([क-ह])/g, '$1ं');

  // 9. 'ज' as 'य' in Devanagari names
  res = res.replace(/ज/g, 'य');

  // Clean double matras if any
  res = res.replace(/([ािीुूेैोौं])\1+/g, '$1');

  return res.trim();
}

function decodeSecHindi(text) {
  if (!text) return '';
  let clean = text
    .replace(/Photo\s*is\s*Available/gi, '')
    .replace(/Available/gi, '')
    .replace(/Photo/gi, '')
    .replace(/is/gi, '')
    .trim();

  if (!clean) return '';

  const words = clean.split(/\s+/);
  const decoded = words.map(w => decodeSecWord(w));
  return decoded.join(' ').replace(/\s{2,}/g, ' ').trim();
}

