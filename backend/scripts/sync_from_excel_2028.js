const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const wb = XLSX.readFile('C:/Users/pc/Downloads/VIDHANSHABHA 2028.xlsx');
const sheet = wb.Sheets['Sheet1'];
const rows = XLSX.utils.sheet_to_json(sheet);

console.log('Total rows in VIDHANSHABHA 2028.xlsx:', rows.length);

// Canonical Samiti Name normalizer
function normalizeSamiti(s) {
  const clean = String(s || '').trim();
  if (clean.includes('रायपुर')) return 'रायपुर';
  if (clean.includes('सहाडा') || clean.includes('सहाड़ा')) return 'सहाड़ा';
  if (clean.includes('सुवाणा')) return 'सुवाणा';
  return clean;
}

// Clean names
function cleanText(t) {
  if (t === null || t === undefined) return '';
  return String(t).trim().replace(/\s+/g, ' ');
}

const hierarchy = {
  'रायपुर': { name: 'रायपुर', wards: {} },
  'सहाड़ा': { name: 'सहाड़ा', wards: {} },
  'सुवाणा': { name: 'सुवाणा', wards: {} }
};

// Village cross-reference map (for common villages)
const villageToWardsMap = {};

rows.forEach((r, idx) => {
  const samiti = normalizeSamiti(r['पंचायत समिति ']);
  if (!hierarchy[samiti]) {
    hierarchy[samiti] = { name: samiti, wards: {} };
  }

  const zilaWardRaw = cleanText(r['जिला परिषद वार्ड संख्या ']);
  const samitiWardRaw = cleanText(r['पंचायत समिति वार्ड संख्या ']);
  const samitiWardNum = samitiWardRaw.replace(/[^\d]/g, '');
  const samitiWardKey = samitiWardNum ? `वार्ड संख्या ${samitiWardNum}` : samitiWardRaw;

  const gpName = cleanText(r['ग्राम पंचायत ']);
  const villageName = cleanText(r['राजस्व ग्राम ']);
  const villagePop = Number(r['ग्राम की जनसंख्या']) || 0;
  const gpPop = Number(r['ग्राम पंचायत की जनसंख्या']) || 0;
  const gpTotalWards = Number(r['ग्राम पंचायत वार्डो की संख्या']) || 0;

  if (!samitiWardKey || !gpName) return;

  const samitiObj = hierarchy[samiti];
  if (!samitiObj.wards[samitiWardKey]) {
    samitiObj.wards[samitiWardKey] = {
      wardNumber: samitiWardNum,
      wardLabel: samitiWardKey,
      zilaWard: zilaWardRaw,
      panchayats: {}
    };
  }

  const wardObj = samitiObj.wards[samitiWardKey];
  if (!wardObj.panchayats[gpName]) {
    wardObj.panchayats[gpName] = {
      name: gpName,
      population: gpPop,
      totalWards: gpTotalWards,
      villages: []
    };
  }

  const gpObj = wardObj.panchayats[gpName];
  if (gpPop > 0 && (!gpObj.population || gpObj.population < gpPop)) {
    gpObj.population = gpPop;
  }
  if (gpTotalWards > 0 && (!gpObj.totalWards || gpObj.totalWards < gpTotalWards)) {
    gpObj.totalWards = gpTotalWards;
  }

  if (villageName && !gpObj.villages.some(v => v.name === villageName)) {
    gpObj.villages.push({
      name: villageName,
      population: villagePop
    });
  }

  // Cross reference
  if (villageName) {
    if (!villageToWardsMap[villageName]) villageToWardsMap[villageName] = [];
    villageToWardsMap[villageName].push({
      samiti,
      samitiWard: samitiWardKey,
      samitiWardNumber: samitiWardNum,
      gramPanchayat: gpName,
      zilaWard: zilaWardRaw,
      population: villagePop
    });
  }
});

// Sort wards numerically for all samitis
for (const [sName, sObj] of Object.entries(hierarchy)) {
  const sortedWards = {};
  const sortedKeys = Object.keys(sObj.wards).sort((a, b) => {
    const numA = parseInt(a.replace(/[^\d]/g, ''), 10) || 0;
    const numB = parseInt(b.replace(/[^\d]/g, ''), 10) || 0;
    return numA - numB;
  });
  sortedKeys.forEach(k => {
    sortedWards[k] = sObj.wards[k];
  });
  sObj.wards = sortedWards;
}

console.log('Hierarchy summary:');
for (const [sName, sObj] of Object.entries(hierarchy)) {
  console.log(`- ${sName}: ${Object.keys(sObj.wards).length} Wards`);
  let totalVillages = 0;
  for (const w of Object.values(sObj.wards)) {
    for (const p of Object.values(w.panchayats)) {
      totalVillages += p.villages.length;
    }
  }
  console.log(`  Total villages: ${totalVillages}`);
}

